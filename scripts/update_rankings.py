#!/usr/bin/env python3
"""Fetch the latest World Rugby men's 15s rankings and write them into index.html.

The rankings live in one block in index.html, between the BEGIN/END RANKINGS DATA
markers. This script regenerates that block; everything on the page is built from it.

Usage:
  python scripts/update_rankings.py                      # fetch from World Rugby
  python scripts/update_rankings.py --from-file r.json   # use a saved API response
"""
import argparse
import json
import re
import sys
import unicodedata
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INDEX = ROOT / "index.html"
TEAMS_FILE = ROOT / "data" / "teams.json"
# World Rugby's rankings feed (hosted by Pulselive). Tried in order; the
# older address is kept as a fallback in case it comes back.
API_URLS = [
    "https://api.wr-rims-prod.pulselive.com/rugby/v3/rankings/mru?language=en",
    "https://api.wr-rugby.com/rugby/v1/rankings/mru",
]
BEGIN = "// BEGIN RANKINGS DATA"
END = "// END RANKINGS DATA"
MIN_TEAMS = 50  # refuse to write a suspiciously short list


def normalise(name):
    """Loose key for matching team names: 'Côte d'Ivoire' == 'Cote D Ivoire'."""
    s = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode().lower()
    s = s.replace("&", " and ")
    s = re.sub(r"[^a-z0-9]+", " ", s)
    s = re.sub(r"\bsaint\b", "st", s)
    s = re.sub(r"\bthe\b", "", s)
    return " ".join(s.split())


def load_lookup(path=TEAMS_FILE):
    teams = json.loads(path.read_text(encoding="utf-8"))["teams"]
    lookup = {}
    for name, info in teams.items():
        for key in [name, *info.get("aliases", [])]:
            lookup[normalise(key)] = (name, info)
    return lookup


def parse_date(effective):
    """World Rugby gives {'label': '2025-10-20', 'millis': ...}; accept either."""
    effective = effective or {}
    label = str(effective.get("label") or "")
    if re.match(r"\d{4}-\d{2}-\d{2}", label):
        return label[:10]
    millis = effective.get("millis")
    if isinstance(millis, (int, float)):
        return datetime.fromtimestamp(millis / 1000, tz=timezone.utc).date().isoformat()
    return None


def parse_api(payload):
    """Return (as_of, [{name, pos, prevPos, pts}]) from a World Rugby rankings response."""
    entries = payload.get("entries") if isinstance(payload, dict) else None
    if not isinstance(entries, list) or not entries:
        raise ValueError("Response has no 'entries' list - has the World Rugby API changed?")
    rows = []
    for e in entries:
        try:
            rows.append({
                "name": e["team"]["name"],
                "pos": int(e["pos"]),
                "prevPos": int(e["previousPos"]) if e.get("previousPos") is not None else None,
                "pts": round(float(e["pts"]), 2),
            })
        except (KeyError, TypeError, ValueError) as exc:
            raise ValueError(f"Unexpected entry format {e!r}: {exc}") from exc
    return parse_date(payload.get("effective")), rows


def build(as_of, rows, lookup):
    """Attach map ids to each team. Returns (data, unmapped_names)."""
    teams, unmapped = [], []
    for r in sorted(rows, key=lambda r: r["pos"]):
        match = lookup.get(normalise(r["name"]))
        name, info = match if match else (r["name"], {})
        if not match:
            unmapped.append(r["name"])
        team = {"name": name, "pos": r["pos"], "prevPos": r["prevPos"], "pts": r["pts"],
                "id": info.get("id")}
        if "dot" in info:
            team["dot"] = info["dot"]
        teams.append(team)
    return {"asOf": as_of, "teams": teams}, unmapped


def validate(data):
    teams = data["teams"]
    if len(teams) < MIN_TEAMS:
        raise ValueError(f"Only {len(teams)} teams in response - not writing it")
    positions = [t["pos"] for t in teams]
    if len(set(positions)) != len(positions):
        raise ValueError("Duplicate ranking positions in response")


def render_block(data):
    lines = [f"{BEGIN} (generated by scripts/update_rankings.py - don't edit by hand)",
             "const RANKINGS = {",
             f'  "asOf": {json.dumps(data["asOf"])},',
             '  "teams": [']
    rows = [json.dumps(t, ensure_ascii=False) for t in data["teams"]]
    lines += [f"    {row}," for row in rows[:-1]] + [f"    {rows[-1]}"]
    lines += ["  ]", "};", END]
    return "\n".join(lines)


def write_index(block, path=INDEX):
    html = path.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if len(pattern.findall(html)) != 1:
        raise ValueError(f"Expected exactly one rankings data block in {path.name}")
    new = pattern.sub(lambda _: block, html)
    changed = new != html
    if changed:
        path.write_text(new, encoding="utf-8")
    return changed


def fetch(urls=API_URLS):
    """Return the first rankings response that can be fetched and parsed."""
    errors = []
    for url in urls:
        req = urllib.request.Request(url, headers={
            "User-Agent": "rugby-rankings-updater (+https://github.com/lamceol/rugby-rankings)",
            "Accept": "application/json",
        })
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                payload = json.load(resp)
            parse_api(payload)  # make sure it's a rankings response before using it
            print(f"Fetched rankings from {url}")
            return payload
        except Exception as exc:  # network error, bad JSON or unexpected format
            print(f"::warning::Couldn't use {url}: {exc}")
            errors.append(f"{url}: {exc}")
    raise RuntimeError("No World Rugby rankings source worked:\n  " + "\n  ".join(errors))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--from-file", type=Path, help="read a saved API response instead of fetching")
    args = ap.parse_args(argv)

    payload = json.loads(args.from_file.read_text()) if args.from_file else fetch()
    as_of, rows = parse_api(payload)
    data, unmapped = build(as_of, rows, load_lookup())
    validate(data)

    for name in unmapped:
        # GitHub Actions shows this as a warning on the run
        print(f"::warning::'{name}' isn't in data/teams.json, so it won't appear on the map")
    changed = write_index(render_block(data))
    print(f"{'Updated' if changed else 'No change to'} rankings: "
          f"{len(data['teams'])} teams, as of {as_of or 'unknown date'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
